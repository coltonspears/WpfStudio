using System.Collections.Concurrent;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CodeActions;
using Microsoft.CodeAnalysis.Text;
using WpfStudio.Contracts;

namespace WpfStudio.Workspace;

public sealed partial class WorkspaceEngine
{
    // Only the most recent Ctrl+. request is kept, with the solution snapshot its actions were computed from.
    private readonly ConcurrentDictionary<string, (Document Document, long Version, CodeAction Action)> _codeActions = new();
    private long _codeActionRequest;

    public async Task<CodeActionsResult> GetCodeActionsAsync(CodeActionsRequest request, CancellationToken cancellationToken)
    {
        await EnsurePageProjectionAsync(cancellationToken).ConfigureAwait(false);
        Document document;
        long generation;
        lock (_gate)
        {
            document = GetDocument(request.Path, request.Version);
            generation = ++_codeActionRequest;
            _codeActions.Clear();
        }
        var text = await document.GetTextAsync(cancellationToken).ConfigureAwait(false);
        ValidatePosition(request.Start, text.Length);
        var span = new TextSpan(request.Start, Math.Clamp(request.Length, 0, text.Length - request.Start));
        var candidates = await CodeActionCatalog.GetAsync(document, span, cancellationToken).ConfigureAwait(false);
        var entries = new List<CodeActionEntry>(candidates.Count);
        lock (_gate)
        {
            if (generation != _codeActionRequest || _pageProjectionPending || !ReferenceEquals(document.Project.Solution, _solution))
                return new(request.Version, []);
            foreach (var candidate in candidates)
            {
                var id = Guid.NewGuid().ToString("N");
                _codeActions[id] = (document, request.Version, candidate.Action);
                entries.Add(new(id, candidate.Title, candidate.Kind));
            }
        }
        return new(request.Version, entries);
    }

    public async Task<WorkspaceEditResult> ApplyCodeActionAsync(ApplyCodeActionRequest request, CancellationToken cancellationToken)
    {
        await EnsurePageProjectionAsync(cancellationToken).ConfigureAwait(false);
        _ = GetDocument(request.Path, request.Version);
        if (!_codeActions.TryGetValue(request.Id, out var entry) || entry.Version != request.Version
            || !string.Equals(entry.Document.FilePath, Path.GetFullPath(request.Path), StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException("This quick action is no longer available. Press Ctrl+. again.");
        var original = entry.Document.Project.Solution;
        lock (_gate)
            if (!ReferenceEquals(original, _solution)) throw new InvalidOperationException("The workspace changed after the quick actions were listed. Press Ctrl+. again.");
        var changes = await CodeActionCatalog.GetChangesAsync(entry.Action, original, cancellationToken).ConfigureAwait(false)
            ?? throw new InvalidOperationException("This action needs an options dialog or deletes files, which WpfStudio does not support yet.");
        var documents = new List<DocumentEdits>();
        var warnings = new List<string>();
        Dictionary<string, long> versions;
        lock (_gate) versions = new(_versions, StringComparer.OrdinalIgnoreCase);
        foreach (var change in changes)
        {
            // Compiler output is regenerated by the build; an action's edit to it would be lost.
            if (IsGenerated(change.Path)) { warnings.Add($"Skipped generated file {Path.GetFileName(change.Path)}."); continue; }
            documents.Add(change.Before is null
                ? new DocumentEdits(change.Path, 0, change.Changes.Select(ToEdit).ToArray(), null, Create: true)
                : new DocumentEdits(change.Path, versions.GetValueOrDefault(Path.GetFullPath(change.Path)), change.Changes.Select(ToEdit).ToArray(), TextHash(change.Before.ToString())));
        }
        if (documents.Count == 0) throw new InvalidOperationException("This action does not change any source file.");
        return new(documents, warnings);
    }
}
