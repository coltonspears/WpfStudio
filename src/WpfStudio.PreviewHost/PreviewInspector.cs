using System.Globalization;
using System.Reflection;
using System.Windows;
using System.Windows.Data;
using System.Windows.Markup;
using WpfStudio.Contracts;
using WpfStudio.Inspection.Protocol;
using WpfStudio.Wpf.Diagnostics;
using WpfStudio.Wpf.PropertyEditing;

namespace WpfStudio.PreviewHost;

/// <summary>Reads one object's properties and bindings for the inspector, and applies temporary property edits.</summary>
internal sealed partial class PreviewInspector(PreviewScene scene, PreviewVisualTree tree, PreviewLayoutEditing layout, PreviewDiagnosticLog log) : IDisposable
{
    // Created before any preview XAML or project view is loaded. The collector
    // retains bounded copied facts and weak identities, never a model graph.
    private readonly BindingEvidenceCollector _bindingEvidence = new(TemporaryPropertyEdits.IsOverrideBinding);
    private readonly StaticResourceEvidenceCollector _appearanceEvidence = new();
    private TemporaryPropertyEdits _edits = new();

    public void ForgetAppearanceEvidence() => _appearanceEvidence.Clear();

    public void ResetEdits()
    {
        foreach (var weak in _edits.GetEditedTargets())
            if (weak.TryGetTarget(out var target)) _edits.ResetAll(target);
        _edits = new();
    }

    public void ForgetBindings()
    {
        _bindingSources = new();
        _bindingEvidence.Clear();
    }

    public void Dispose()
    {
        _appearanceEvidence.Dispose();
        _bindingEvidence.Dispose();
    }

    public PreviewInspection Pick(PreviewPickRequest request)
    {
        if (request.Version != scene.Version || scene.Viewport is null) return Empty("The preview has changed. Refresh the selection.");
        if (!double.IsFinite(request.X) || !double.IsFinite(request.Y) || request.X < 0 || request.Y < 0 || request.X >= scene.Width || request.Y >= scene.Height)
            return Empty("The point is outside the preview.");
        DependencyObject? hit = scene.Viewport.InputHitTest(new Point(request.X, request.Y)) as DependencyObject;
        while (hit is not null && !tree.Contains(hit)) hit = PreviewVisualTree.VisualParent(hit);
        if (request.PreferAuthored && scene.Document is not null)
        {
            // Designers select what the author wrote: a click on a button's text
            // selects the Button, not the TextBlock generated by its template.
            for (var candidate = hit; candidate is not null; candidate = PreviewVisualTree.VisualParent(candidate))
                if (tree.Contains(candidate) && scene.Document.FindSource(candidate, ReferenceEquals(candidate, scene.Root)) is not null) { hit = candidate; break; }
        }
        return hit is not null ? Inspect(request.Version, tree.IdOf(hit)!) : Empty("No element at this point.");
    }

    public PreviewInspection Empty(string status) => new(scene.Version, null, [], [], status);

    /// <returns>Why the value was refused, or null when it applied.</returns>
    public string? ApplyEdit(PreviewPropertyEdit request)
    {
        if (request.Version != scene.Version || !tree.TryGet(request.NodeId, out var target))
            throw new InvalidOperationException("The preview has changed. Refresh the selection.");
        var property = tree.FindProperty(target, request);
        // Trace output describes the previous evaluation. Current binding
        // expression status below is the authority after a live edit.
        log.ClearTrace();
        var edited = request.Reset ? _edits.Reset(target, property) : _edits.Apply(target, property, request.Value, request.Value is null);
        return edited.Success ? null : edited.Error;
    }

    public PreviewPropertyValidation ValidateProperty(PreviewPropertyEdit request)
    {
        try
        {
            if (request.Version != scene.Version || !tree.TryGet(request.NodeId, out var target))
                throw new InvalidOperationException("The preview has changed. Refresh the selection.");
            var property = tree.FindProperty(target, request);
            if (request.Reset || property.ReadOnly || !ScalarPropertyValues.Supports(property.PropertyType))
                throw new InvalidOperationException("This property does not support writing a scalar value.");
            if (scene.Document is not null && !scene.Document.CanWriteProperty(target, property, PreviewVisualTree.IsAttached(property, target)))
                throw new InvalidOperationException("The authored XAML element does not expose this writable property.");
            if (scene.Document?.IsDesignTimeProperty(target, property) == true || scene.ScenarioActivation?.IsDataContextProperty(target, property) == true)
                throw new InvalidOperationException("This property uses a design-time value or scenario data. Runtime XAML writeback is unavailable for that preview override.");
            if (!ScalarPropertyValues.TryConvert(property.PropertyType, request.Value, request.Value is null, out var value, out var error))
                throw new InvalidOperationException(error);
            if (!property.IsValidValue(value))
                throw new InvalidOperationException("The value is not valid for this property.");
            return new PreviewPropertyValidation(true);
        }
        catch (Exception exception) { return new PreviewPropertyValidation(false, exception.GetBaseException().Message); }
    }

    public AppearanceResponse GetAppearance(AppearanceRequest request)
    {
        AppearanceSnapshot captured;
        try
        {
            if (request.Revision != scene.Version || !tree.TryGet(request.NodeId, out var target) || !tree.IsInCurrentPreview(target))
                captured = AppearanceSnapshot.Unavailable("The preview or selected element has changed. Refresh the selection.");
            else
            {
                var property = tree.FindProperty(target, new PreviewPropertyEdit(request.Revision, request.NodeId,
                    request.Property, null, OwnerType: request.OwnerType, OwnerAssembly: request.OwnerAssembly));
                captured = ResourceStyleReader.Capture(target, property, _appearanceEvidence);
            }
        }
        catch (Exception exception) { captured = AppearanceSnapshot.Unavailable(exception.GetBaseException().Message); }
        return new AppearanceResponse(request, captured);
    }

    public PreviewInspection Inspect(long version, string nodeId)
    {
        if (version != scene.Version || !tree.TryGet(nodeId, out var target)) return Empty("The preview has changed. Refresh the selection.");
        string? contextType = target is FrameworkElement element ? element.DataContext?.GetType().FullName : target is FrameworkContentElement content ? content.DataContext?.GetType().FullName : null;
        var properties = new List<PreviewProperty>();
        var diagnostics = new List<PreviewDiagnostic>();
        int bindingRowsRemaining = 256, bindingCharactersRemaining = 131072;
        var bindingBudget = new BindingDetailBudget(65536);
        foreach (var property in tree.Properties(target))
        {
            try
            {
                var source = DependencyPropertyHelper.GetValueSource(target, property);
                BindingExpressionBase? expression = BindingOperations.GetBindingExpressionBase(target, property);
                bool scenarioData = scene.ScenarioActivation?.IsDataContextProperty(target, property) == true;
                bool ownsScenarioData = scene.ScenarioActivation?.OwnsDataContext(target, property) == true;
                bool designTime = scene.Document?.IsDesignTimeProperty(target, property) == true;
                if (TemporaryPropertyEdits.IsOverrideBinding(expression) || ownsScenarioData) expression = null;
                string? path = expression is BindingExpression binding ? binding.ParentBinding.Path?.Path : expression is MultiBindingExpression ? "(MultiBinding)" : expression is PriorityBindingExpression ? "(PriorityBinding)" : null;
                string propertyName = PreviewVisualTree.PropertyName(property, target);
                object? value = target.GetValue(property);
                var observation = expression is null ? null : bindingBudget.Take(BindingReader.Read(expression, _bindingEvidence));
                var bindingSources = CaptureBindingSources(expression, ref bindingRowsRemaining, ref bindingCharactersRemaining, bindingBudget);
                var editInfo = _edits.Describe(target, property);
                string? editableValue = editInfo.EditableValue;
                properties.Add(new PreviewProperty(propertyName, property.PropertyType.FullName ?? property.PropertyType.Name,
                    Format(value), editInfo.IsOverridden && designTime ? "Preview override (design baseline)" : ownsScenarioData ? "Scenario" :
                        source.BaseValueSource + (designTime ? " (design baseline)" : ""), source.IsExpression, source.IsAnimated,
                    source.IsCoerced, editInfo.CanEdit, path, expression?.Status.ToString(), contextType,
                    editInfo.IsOverridden, property.OwnerType.FullName, property.OwnerType.Assembly.GetName().Name,
                    PreviewVisualTree.IsAttached(property, target), editableValue, !scenarioData && !designTime && !property.ReadOnly && ScalarPropertyValues.Supports(property.PropertyType) &&
                        scene.Document?.CanWriteProperty(target, property, PreviewVisualTree.IsAttached(property, target)) == true,
                    target.GetType().GetCustomAttribute<ContentPropertyAttribute>(inherit: true)?.Name,
                    bindingSources, observation));
                if (observation is not null && IsBindingFailure(observation))
                    diagnostics.Add(BindingDiagnostic(nodeId, propertyName, observation, bindingSources?.BindingId));
            }
            catch (Exception exception) { diagnostics.Add(new PreviewDiagnostic($"Cannot inspect {property.Name}: {exception.GetBaseException().Message}", "Warning", NodeId: nodeId, Property: property.Name)); }
        }
        return new PreviewInspection(scene.Version, tree.Node(target), properties.OrderBy(p => p.Name, StringComparer.Ordinal).ToArray(), diagnostics,
            Layout: scene.Viewport is null ? null : Wpf.Diagnostics.LayoutReader.Capture(target, scene.Viewport), LayoutEditing: layout.Capture(target));
    }

    public (PreviewDiagnostic Diagnostic, bool UnavailableDataContext)[] BindingFailures() =>
        tree.Objects.SelectMany(pair => BindingFailures(pair.Key, pair.Value)).ToArray();

    private IEnumerable<(PreviewDiagnostic Diagnostic, bool UnavailableDataContext)> BindingFailures(string nodeId, DependencyObject target)
    {
        foreach (var property in tree.Properties(target))
        {
            var expression = BindingOperations.GetBindingExpressionBase(target, property);
            if (expression is null || TemporaryPropertyEdits.IsOverrideBinding(expression) || scene.ScenarioActivation?.OwnsDataContext(target, property) == true) continue;
            var observation = BindingReader.Read(expression, _bindingEvidence);
            if (!IsBindingFailure(observation)) continue;
            string id = _bindingSources.Capture(expression, maximumDeclarations: 0, maximumCharacters: 0).BindingId;
            yield return (BindingDiagnostic(nodeId, PreviewVisualTree.PropertyName(property, target), observation, id),
                observation.Category == "SourceUnavailable" && observation.Details?.SourceKind == "DataContextOrNullSource");
        }
    }

    private static string Format(object? value)
    {
        if (value is null) return "(null)";
        string text = value is IFormattable formatted ? formatted.ToString(null, CultureInfo.InvariantCulture) : value.ToString() ?? "";
        return text.Length > 2000 ? text[..2000] + "…" : text;
    }
}
